"""Compare the Git-tracked PDF inventory with the reviewed public download list."""
from pathlib import Path
import subprocess
import argparse
import filecmp

root = Path(__file__).resolve().parents[1]
known = set((root / "scripts/public-pdf-paths.txt").read_text(encoding="utf-8").splitlines())
tracked = subprocess.check_output(["git", "ls-files", "-z"], cwd=root).decode("utf-8").split("\0")
actual = {name for name in tracked if name.lower().endswith(".pdf")}
unexpected = actual - known
missing = known - actual
if unexpected or missing:
    for name in sorted(unexpected):
        print(f"Unreviewed PDF in public repository: {name}")
    for name in sorted(missing):
        print(f"Reviewed public delivery path is missing: {name}")
    raise SystemExit(1)
print(f"Verified {len(actual)} reviewed public PDF paths.")

parser = argparse.ArgumentParser()
parser.add_argument("--site", type=Path, help="Verify these paths in the generated Pages site.")
site = parser.parse_args().site
if site is not None:
    files = known | {
        "build-your-flock-embed.html", "build-your-flock-data.json",
        "garden-events-runtime.js", "garden-events-data.json", "garden-conditions-data.json",
        "local-resources-embed.html", "local-resources-data.json",
        "ah-site-scripts.js", "related-manifest.json",
    }
    for path in sorted(files):
        published = site / path
        if not published.is_file() or not filecmp.cmp(root / path, published, shallow=False):
            raise SystemExit(f"Generated site is missing or modified a public asset: {path}")
    if (site / "scripts/check_public_downloads.py").exists() or (site / "build-your-flock/tests").exists():
        raise SystemExit("The generated site includes source-only files.")
    print(f"Verified exact generated bytes for {len(files)} tool and fulfillment assets.")
