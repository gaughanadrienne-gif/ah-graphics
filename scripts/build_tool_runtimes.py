"""Build public tool runtimes from canonical embed sources. No eval or inline script injection.

The shared site script mounts these after legacy native embeds finish loading.
Namespaced roots isolate late legacy async writers; native roots become hidden inert sinks.
Run after editing either embed, or --check to reject stale generated assets.
"""
from pathlib import Path
import argparse, hashlib, json, re
ROOT = Path(__file__).resolve().parents[1]
TOOLS = [("garden-events", "#garden-events-tool")]

def build(name, root_id):
    source = (ROOT / (name + "-embed.html")).read_text(encoding="utf-8")
    scripts = re.findall(r"<script[^>]*>([\s\S]*?)</script>", source, re.I)
    assert len(scripts) == 1, "Expected exactly one executable tool script"
    styles = re.findall(r"<style[^>]*>([\s\S]*?)</style>", source, re.I)
    markup = re.sub(r"<script[^>]*>[\s\S]*?</script>", "", source, flags=re.I)
    markup = re.sub(r"<style[^>]*>[\s\S]*?</style>", "", markup, flags=re.I)
    # Namespace public IDs so a late native async callback cannot overwrite the new UI.
    ids = {key: "ah-live-"+key for key in re.findall(r'\bid="([^"]+)"', markup)}
    for old_id,new_id in ids.items():
        for attr in ("id", "for", "aria-controls", "aria-labelledby"):
            markup=markup.replace(attr+'="'+old_id+'"', attr+'="'+new_id+'"')
        markup=markup.replace('href="#'+old_id+'"', 'href="#'+new_id+'"')
        styles=[re.sub(r"#"+re.escape(old_id)+r"(?![\w-])", "#"+new_id, css) for css in styles]
    selector="#"+ids[root_id[1:]] if root_id.startswith("#") else root_id
    revision = hashlib.sha256((source+"|runtime-format-2").encode()).hexdigest()[:16]
    executable=scripts[0].replace("document.getElementById(","ahToolElement(")
    return ("// Generated by scripts/build_tool_runtimes.py. Source revision: " + revision + "\n" +
        "(function(){\nvar old=document.querySelector("+json.dumps(root_id)+");\n" +
        "if(!old||old.dataset.ahRuntime==="+json.dumps(revision)+")return;\n" +
        "var template=document.createElement('template');template.innerHTML="+json.dumps(markup)+";\n" +
        "var next=template.content.querySelector("+json.dumps(selector)+");if(!next)return;\n" +
        "next.dataset.ahRuntime="+json.dumps(revision)+";old.before(next);old.hidden=true;old.inert=true;old.setAttribute('aria-hidden','true');old.style.setProperty('display','none','important');old.className='';old.dataset.ahLegacySink='true';old.dataset.ahRuntime="+json.dumps(revision)+";\n" +
        "var style=document.getElementById("+json.dumps(name+"-runtime-style")+")||document.createElement('style');\n" +
        "style.id="+json.dumps(name+"-runtime-style")+";style.textContent="+json.dumps("\n".join(styles))+";document.head.appendChild(style);\n" +
        "var ids="+json.dumps(ids)+";function ahToolElement(id){return document.getElementById(ids[id]||id);}" + executable + "\n})();\n")

def main():
    parser=argparse.ArgumentParser();parser.add_argument("--check",action="store_true");args=parser.parse_args()
    loader=ROOT/"ah-site-scripts.js"; loader_source=loader.read_bytes()
    for name,root_id in TOOLS:
        path=ROOT/(name+"-runtime.js");expected=build(name,root_id)
        if args.check:
            assert path.read_text(encoding="utf-8")==expected, str(path)+" is stale"
        else:
            path.write_text(expected,encoding="utf-8",newline="\n")
        revision=re.search(r"Source revision: ([a-f0-9]+)",expected).group(1)
        pattern=(name+r"-runtime\.js\?v=[a-f0-9]+").encode()
        asset=(name+"-runtime.js?v="+revision).encode()
        assert len(re.findall(pattern,loader_source))==1, "Missing tool loader entry"
        updated=re.sub(pattern,asset,loader_source)
        if args.check: assert updated==loader_source, name+" loader revision is stale"
        loader_source=updated
        print(name+": "+("verified" if args.check else "generated"))
    if not args.check: loader.write_bytes(loader_source)
if __name__=="__main__": main()
