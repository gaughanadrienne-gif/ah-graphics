/**
 * Derives the compact crop dataset embedded in what-to-plant-this-week-embed.html
 * from the canonical planting calendar data (READ ONLY source):
 *   Website/planting-calendar-data.js
 *
 * This script does not modify the source file or the planting-calendar tool.
 * It only prints a compact JS object literal (same key convention as
 * planting-calendar-embed-v3.html: s/n/c/d/a/z{i,d,x,h}) to stdout, which gets
 * pasted into the DATA block of what-to-plant-this-week-embed.html.
 *
 * Re-run and re-paste whenever planting-calendar-data.js changes (new crops,
 * corrected months, etc). This mirrors how the main calendar tool already
 * keeps its own embedded copy in sync with the source file: both are static
 * embeds regenerated by hand, not live fetches.
 *
 * Usage:
 *   node build-what-to-plant-week-data.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SOURCE = path.resolve(__dirname, '..', '..', 'planting-calendar-data.js');

const src = fs.readFileSync(SOURCE, 'utf-8');

// Evaluate the data literal in an isolated function scope. Read-only: we never
// write back to SOURCE.
const load = new Function(src + '\nreturn PLANTING_CALENDAR_DATA;');
const data = load();

const zoneKeys = Object.keys(data.zones);

function compactCrop(cr) {
  const z = {};
  for (const zk of zoneKeys) {
    const zd = cr.zones[zk];
    if (!zd) continue;
    z[zk] = {
      i: zd.sowIndoors || [],
      d: zd.directSow || [],
      x: zd.transplant || [],
      h: zd.harvest || []
    };
  }
  return {
    s: cr.slug,
    n: cr.name,
    c: cr.category,
    d: cr.difficulty,
    a: cr.articleSlug || null,
    z
  };
}

const compactCrops = data.crops.map(compactCrop);

const compactZones = {};
for (const zk of zoneKeys) {
  const zi = data.zones[zk];
  // characteristics/avgLastFrost/avgFirstFrost are kept (not just name+usda)
  // because the "What to Plant This Week" widget uses them to explain real
  // zone-month gaps (e.g. mountain Nov-Dec, desert May-Jul) in the zone's own
  // words instead of rendering a bare empty state.
  compactZones[zk] = {
    name: zi.name,
    usdaZones: zi.usdaZones,
    avgLastFrost: zi.avgLastFrost,
    avgFirstFrost: zi.avgFirstFrost,
    characteristics: zi.characteristics
  };
}

// Print as a single-line-per-crop JS literal, matching the style already used
// in planting-calendar-embed-v3.html so a human diff between the two is easy.
function jsStr(v) { return JSON.stringify(v); }

let out = 'zones:' + jsStr(compactZones) + ',\n';
out += 'zip:' + jsStr(data.zipToZone) + ',\n';
out += 'crops:[\n';
out += compactCrops.map(cr => {
  const zParts = Object.entries(cr.z).map(([zk, zd]) =>
    zk + ':{i:' + jsStr(zd.i) + ',d:' + jsStr(zd.d) + ',x:' + jsStr(zd.x) + ',h:' + jsStr(zd.h) + '}'
  ).join(',');
  return '{s:' + jsStr(cr.s) + ',n:' + jsStr(cr.n) + ',c:' + jsStr(cr.c) + ',d:' + jsStr(cr.d) +
    ',a:' + jsStr(cr.a) + ',z:{' + zParts + '}}';
}).join(',\n');
out += '\n]';

process.stdout.write(out + '\n');
